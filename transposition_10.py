print("A. Encryption")
print("B. Decryption")
op = input("Enter your choice: ").upper()

if op == "A":
    key = input("Key in digits: ")
    pt = input("Plaintext: ").upper().replace(" ", "")

    if key.isdigit() and pt.isalpha():
        n = len(key)
        cols = sorted(range(n), key=lambda i: key[i])

        ct = "".join(pt[i::n] for i in cols)
        print("Ciphertext:", ct)
    else:
        print("Invalid Input!")

elif op == "B":
    key = input("Key in digits: ")
    ct = input("Ciphertext: ").upper().replace(" ", "")

    if key.isdigit() and ct.isalpha():
        n = len(key)
        total_len = len(ct)

        short_rows = total_len // n
        extra_chars = total_len % n

        cols = sorted(range(n), key=lambda i: key[i])

        col_lengths = [short_rows + (1 if i < extra_chars else 0) for i in range(n)]

        a = [''] * n
        k = 0
        for i in cols:
            length = col_lengths[i]
            a[i] = ct[k : k + length]
            k += length

        pt_chars = []
        for r in range(short_rows + 1):
            for c in range(n):
                if r < len(a[c]):
                    pt_chars.append(a[c][r])

        pt = "".join(pt_chars)
        print("Plaintext:", pt)
    else:
        print("Invalid Input!")

else:
    print("Invalid choice!")