print("A. Encryption")
print("B. Decryption")
op = input("Enter your choice: ").upper()

if op == "A":
    key = input("Key: ").upper().replace("J", "I")
    pt = "".join(c for c in input("Plaintext: ").upper().replace("J", "I") if c.isalpha())

    if key.isalpha() and pt:
        s = ""
        for c in key + "ABCDEFGHIKLMNOPQRSTUVWXYZ":
            if c not in s and c.isalpha():
                s += c
        m = [s[i:i+5] for i in range(0, 25, 5)]

        def pos(c):
            for i in range(5):
                for j in range(5):
                    if m[i][j] == c: return i, j

        prepared_pt = ""
        i = 0
        while i < len(pt):
            prepared_pt += pt[i]
            if i + 1 < len(pt) and pt[i] == pt[i + 1]:
                prepared_pt += "X"
            elif i + 1 < len(pt):
                prepared_pt += pt[i + 1]
                i += 1
            i += 1

        if len(prepared_pt) % 2 != 0:
            prepared_pt += "X"

        ct = ""
        for k in range(0, len(prepared_pt), 2):
            a, b = prepared_pt[k], prepared_pt[k+1]
            r1, c1 = pos(a); r2, c2 = pos(b)
            if r1 == r2:
                ct += m[r1][(c1+1)%5] + m[r2][(c2+1)%5]
            elif c1 == c2:
                ct += m[(r1+1)%5][c1] + m[(r2+1)%5][c2]
            else:
                ct += m[r1][c2] + m[r2][c1]

        print("Ciphertext:", ct)
    else:
        print("Invalid INPUT")

elif op == "B":
    key = input("Key: ").upper().replace("J", "I")
    ct = "".join(c for c in input("Ciphertext: ").upper().replace("J", "I") if c.isalpha())

    if key.isalpha() and ct and len(ct) % 2 == 0:
        s = ""
        for c in key + "ABCDEFGHIKLMNOPQRSTUVWXYZ":
            if c not in s and c.isalpha():
                s += c

        m = [s[i:i+5] for i in range(0, 25, 5)]

        def pos(c):
            for i in range(5):
                for j in range(5):
                    if m[i][j] == c: return i, j

        pt = ""
        for k in range(0, len(ct), 2):
            a, b = ct[k], ct[k+1]
            r1, c1 = pos(a); r2, c2 = pos(b)

            if r1 == r2:
                pt += m[r1][(c1-1)%5] + m[r2][(c2-1)%5]
            elif c1 == c2:
                pt += m[(r1-1)%5][c1] + m[(r2-1)%5][c2]
            else:
                pt += m[r1][c2] + m[r2][c1]

        print("Plaintext:", pt)
    else:
        print("Invalid INPUT")

else:
    print("Invalid choice")